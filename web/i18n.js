    function normalizeLang(lang) {
        return SUPPORTED_UI_LANGS.has(lang) ? lang : "zh-CN";
    }

    function toTraditional(text) {
        if (ZH_TW_OVERRIDES[text]) return ZH_TW_OVERRIDES[text];
        return String(text).replace(/[\u4e00-\u9fff]/g, ch => ZH_TW_CHAR_MAP[ch] || ch);
    }

    function format(text, params) {
        if (!params) return text;
        return String(text).replace(/\{(\w+)\}/g, (_, key) => params[key] == null ? "" : String(params[key]));
    }

    function t(key, params, lang) {
        const source = String(key == null ? "" : key);
        const uiLang = normalizeLang(lang || window.__uiLanguage || "zh-CN");
        if (uiLang === "zh-CN") return format(source, params);
        if (uiLang === "zh-TW") return format(toTraditional(source), params);
        const value = DICT[uiLang] && DICT[uiLang][source];
        return format(value || source, params);
    }

    function getUiLanguage() {
        return normalizeLang(window.__uiLanguage || document.documentElement.lang || "zh-CN");
    }

    function uiLocale() {
        const lang = getUiLanguage();
        if (lang === "zh-TW") return "zh-TW";
        if (lang === "ja") return "ja-JP";
        if (lang === "en") return "en-US";
        return "zh-CN";
    }

    function translateTextNode(node, lang) {
        if (!textOriginals.has(node)) textOriginals.set(node, node.nodeValue);
        const original = textOriginals.get(node);
        if (!original || !original.trim()) return;
        const lead = original.match(/^\s*/)[0];
        const tail = original.match(/\s*$/)[0];
        const core = original.trim();
        node.nodeValue = lead + t(core, null, lang) + tail;
    }

    function translateAttrs(el, lang) {
        let store = attrOriginals.get(el);
        if (!store) {
            store = {};
            attrOriginals.set(el, store);
        }
        ATTRS.forEach(attr => {
            if (!el.hasAttribute || !el.hasAttribute(attr)) return;
            if (store[attr] == null) store[attr] = el.getAttribute(attr);
            el.setAttribute(attr, t(store[attr], null, lang));
        });
    }

    function shouldSkipContent(el) {
        if (!el || !el.matches) return false;
        return !!el.closest("[data-i18n-skip], .path-text, .log-area, .game-title, .game-date");
    }

    function shouldSkipAttrs(el) {
        if (!el || !el.matches) return false;
        return !!el.closest("[data-i18n-skip], .path-text, .game-title, .game-date");
    }

    function walkAndTranslate(root, lang) {
        if (!root) return;
        const tag = root.nodeType === 1 ? root.tagName : "";
        if (tag && /^(SCRIPT|STYLE|SVG|SYMBOL|PATH|LINE|CIRCLE|POLYLINE|RECT)$/i.test(tag)) return;
        if (root.nodeType === 1) {
            if (!shouldSkipAttrs(root)) translateAttrs(root, lang);
            if (shouldSkipContent(root)) return;
        }
        if (root.nodeType === 3 && shouldSkipContent(root.parentElement)) return;
        if (root.nodeType === 3) {
            translateTextNode(root, lang);
            return;
        }
        let child = root.firstChild;
        while (child) {
            walkAndTranslate(child, lang);
            child = child.nextSibling;
        }
    }

    function applyLanguage(lang) {
        const uiLang = normalizeLang(lang);
        window.__uiLanguage = uiLang;
        document.documentElement.lang = uiLang;
        if (document.title) document.title = "EngAixt";
        walkAndTranslate(document.body, uiLang);
        document.querySelectorAll('select[name="ui_language"]').forEach(el => {
            if (el.value !== uiLang) el.value = uiLang;
        });
        if (typeof window.refreshLocalizedDynamicUi === "function") {
            window.refreshLocalizedDynamicUi();
        }
    }

    function setUiLanguage(lang, applyNow) {
        const uiLang = normalizeLang(lang);
        window.__uiLanguage = uiLang;
        if (applyNow !== false) applyLanguage(uiLang);
    }

